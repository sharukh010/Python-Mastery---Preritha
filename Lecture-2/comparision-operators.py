num1 = 10 
num2 = 20 
# comparision operators will give output in boolean (True/False)
# less than < 
print(num1 < num2) # True 
# greather than > 
print(num1 > num2) # False 
# equal to 
print(num1 == num2) # False 
# less than equal to (<=)
print(num1 <= num2) # True 
# greater than equal to (>=)
print(num1 >= num2) # False 
# not equal (!=)
print(num1 != num2) # True 